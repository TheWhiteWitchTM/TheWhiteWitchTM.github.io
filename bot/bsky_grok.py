def service_token(session: dict, token: str) -> str:
    # Video upload wants a short token for this account's PDS, scoped to uploadBlob.
    exp = int(time.time()) + 30 * 60
    query = urllib.parse.urlencode({
        "aud": pds_audience(session),
        "lxm": "com.atproto.repo.uploadBlob",
        "exp": str(exp),
    })
    bases = [pds_of(session), ENTRYWAY]
    last = "no token"
    for base in bases:
        try:
            result = request(f"{base}/xrpc/com.atproto.server.getServiceAuth?{query}", token, timeout=30)
        except SystemExit as err:
            last = str(err)
            continue
        got = result.get("token") or ""
        if got:
            return got
        last = "empty service token"
    raise SystemExit(f"This account cannot upload video. {last}")


def upload_video(auth: str, did: str, path: Path) -> dict:
    blob = path.read_bytes()
    if len(blob) < 1000:
        raise SystemExit(f"Video at {path} is too small.")
    if len(blob) > 50_000_000:
        raise SystemExit(f"Video is {len(blob)} bytes, over the Bluesky limit.")
    query = urllib.parse.urlencode({"did": did, "name": path.name})
    started = request(
        f"{VIDEO_SERVICE}/xrpc/app.bsky.video.uploadVideo?{query}",
        auth,
        raw=blob,
        content_type="video/mp4",
        timeout=180,
    )
    job = started.get("jobStatus") or started
    job_id = started.get("jobId") or job.get("jobId") or ""
    if not job_id:
        raise SystemExit("Video upload did not start.")
    deadline = time.time() + 240
    while time.time() < deadline:
        time.sleep(2)
        status = request(
            f"{VIDEO_SERVICE}/xrpc/app.bsky.video.getJobStatus?{urllib.parse.urlencode({'jobId': job_id})}",
            auth,
            timeout=30,
        )
        job = status.get("jobStatus") or status
        state = str(job.get("state") or "")
        if state in {"JOB_STATE_COMPLETED", "completed"} and job.get("blob"):
            return job["blob"]
        if state in {"JOB_STATE_FAILED", "failed"}:
            raise SystemExit(str(job.get("error") or "Video processing failed."))
    raise SystemExit("Video processing took too long.")


