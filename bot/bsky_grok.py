def last_public_at(state: dict, now: datetime) -> datetime | None:
    latest = None
    for key in (*SLOTS, "video", "paypal", "release"):
        raw = (state.get(key) or {}).get("at")
        if not raw:
            continue
        then = datetime.fromisoformat(raw)
        if then.tzinfo is None:
            then = then.replace(tzinfo=now.tzinfo)
        then = then.astimezone(now.tzinfo)
        if latest is None or then > latest:
            latest = then
    return latest


def too_soon(state: dict, slot: str, now: datetime) -> bool:
    last = (state.get(slot) or {}).get("at")
    if not last:
        return False
    then = datetime.fromisoformat(last)
    if then.tzinfo is None:
        then = then.replace(tzinfo=now.tzinfo)
    then = then.astimezone(now.tzinfo)
    # One politics post and one joke per Berlin day, even if a timer catches up late.
    if slot in {"politics", "joke"}:
        return then.date() == now.date()
    return now - then < GAP


