# --- Bluesky ---------------------------------------------------------------

def request(
    url: str,
    token: str | None,
    payload: dict | None = None,
    raw: bytes | None = None,
    content_type: str | None = None,
    timeout: int = 60,
) -> dict:
    headers = {"Accept": "application/json"}
    if token:
        headers["Authorization"] = f"Bearer {token}"
    data = None
    if raw is not None:
        data = raw
        headers["Content-Type"] = content_type or "application/octet-stream"
    elif payload is not None:
        data = json.dumps(payload).encode("utf-8")
        headers["Content-Type"] = "application/json"
    req = urllib.request.Request(url, data=data, headers=headers)
    try:
        with urllib.request.urlopen(req, timeout=timeout) as res:
            body = res.read()
            return json.loads(body) if body else {}
    except urllib.error.HTTPError as err:
        detail = err.read().decode("utf-8", "replace")[:500]
        raise SystemExit(f"Bluesky {err.code} on {url}: {detail}") from None
    except urllib.error.URLError as err:
        raise SystemExit(f"Bluesky network error on {url}: {err.reason}") from None


def pds_of(session: dict) -> str:
    doc = session.get("didDoc") or {}
    for service in doc.get("service") or []:
        sid = service.get("id") or ""
        if sid.endswith("atproto_pds") and service.get("serviceEndpoint"):
            return service["serviceEndpoint"].rstrip("/")
    return "https://cordyceps.us-west.host.bsky.network"


def create_session(env: dict) -> tuple[dict, str]:
    session = request(
        f"{ENTRYWAY}/xrpc/com.atproto.server.createSession",
        None,
        {"identifier": env["BSKY_HANDLE"], "password": env["BSKY_PASSWORD"]},
    )
    return session, session["accessJwt"]


def upload_image(base: str, token: str, path: Path) -> dict:
    blob = path.read_bytes()
    if len(blob) > 1_000_000:
        raise SystemExit(f"Image is {len(blob)} bytes, over the Bluesky limit.")
    result = request(
        f"{base}/xrpc/com.atproto.repo.uploadBlob",
        token,
        raw=blob,
        content_type="image/jpeg",
    )
    return result["blob"]


def facet_for(text: str, url: str) -> dict:
    start = text.rfind(url)
    if start < 0:
        raise SystemExit("Link missing from post text.")
    byte_start = len(text[:start].encode("utf-8"))
    byte_end = byte_start + len(url.encode("utf-8"))
    return {
        "index": {"byteStart": byte_start, "byteEnd": byte_end},
        "features": [{"$type": "app.bsky.richtext.facet#link", "uri": url}],
    }


def link_facets(text: str) -> list[dict]:
    facets = []
    for match in re.finditer(r"https://[^\s]+", text):
        url = match.group(0).rstrip(".,);]")
        if not url:
            continue
        byte_start = len(text[: match.start()].encode("utf-8"))
        byte_end = byte_start + len(url.encode("utf-8"))
        facets.append(
            {
                "index": {"byteStart": byte_start, "byteEnd": byte_end},
                "features": [{"$type": "app.bsky.richtext.facet#link", "uri": url}],
            }
        )
    return facets


def publish(session: dict, token: str, text: str, image: Path, alt: str, link: str | None = LINK, width: int = W, height: int = H) -> str:
    did = session["did"]
    base = pds_of(session)
    try:
        blob = upload_image(base, token, image)
    except SystemExit:
        base = ENTRYWAY
        blob = upload_image(base, token, image)
    record = {
        "$type": "app.bsky.feed.post",
        "text": text,
        "createdAt": datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%S.%f")[:-3] + "Z",
        "langs": ["en"],
        "embed": {
            "$type": "app.bsky.embed.images",
            "images": [
                {
                    "alt": alt[:1000],
                    "image": blob,
                    "aspectRatio": {"width": width, "height": height},
                }
            ],
        },
    }
    facets = link_facets(text)
    if not facets and link and link in text:
        facets = [facet_for(text, link)]
    if facets:
        record["facets"] = facets
    created = request(
        f"{base}/xrpc/com.atproto.repo.createRecord",
        token,
        {"repo": did, "collection": "app.bsky.feed.post", "record": record},
    )
    uri = created.get("uri", "")
    rkey = uri.rsplit("/", 1)[-1]
    return f"https://bsky.app/profile/{session.get('handle', HANDLE_DEFAULT)}/post/{rkey}"


