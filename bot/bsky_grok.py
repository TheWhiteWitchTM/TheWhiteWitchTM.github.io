def tokens(text: str) -> set[str]:
    words = re.findall(r"[a-z0-9]{4,}", text.lower())
    return {word for word in words if word not in TOKEN_STOP}


def jaccard(left: set[str], right: set[str]) -> float:
    if not left or not right:
        return 0.0
    return len(left & right) / len(left | right)


def targets_of(title: str) -> list[str]:
    found = []
    if TRUMP_RE.search(title):
        found.append("trump")
    if MUSK_RE.search(title):
        found.append("musk")
    if MAGA_RE.search(title):
        found.append("maga")
    return found


def split_title(title: str) -> tuple[str, str]:
    title = html.unescape(title or "")
    title = re.sub(r"\s+", " ", title).strip()
    title = re.sub(r"^(Exclusive|BREAKING|Watch)\s*\|\s*", "", title, flags=re.I)
    if " - " in title:
        head, source = title.rsplit(" - ", 1)
        if 1 < len(source) <= 42 and not source.lower().startswith("http"):
            return head.strip(), source.strip()
    return title, ""


def fetch_bytes(url: str, timeout: int = 20) -> bytes:
    req = urllib.request.Request(
        url,
        headers={"User-Agent": USER_AGENT, "Accept": "application/rss+xml, application/xml, text/xml, */*"},
    )
    with urllib.request.urlopen(req, timeout=timeout) as res:
        return res.read(300_000)


def parse_news(body: bytes) -> list[dict]:
    root = ET.fromstring(body)
    found = []
    now = datetime.now(timezone.utc)
    for item in root.findall("./channel/item")[:25]:
        headline, source = split_title(item.findtext("title") or "")
        targets = targets_of(headline)
        if len(headline) < 24 or not targets:
            continue
        try:
            when = parsedate_to_datetime(item.findtext("pubDate") or "")
        except (TypeError, ValueError, IndexError):
            continue
        if when.tzinfo is None:
            when = when.replace(tzinfo=timezone.utc)
        if now - when > timedelta(hours=30):
            continue
        found.append(
            {
                "headline": headline,
                "source": source,
                "when": when,
                "targets": targets,
                "toks": tokens(headline),
            }
        )
    return found


def gather_stories() -> list[dict]:
    found: list[dict] = []
    for url in NEWS_FEEDS.values():
        try:
            found.extend(parse_news(fetch_bytes(url)))
        except (urllib.error.URLError, TimeoutError, ET.ParseError, OSError) as exc:
            log(f"politics feed skipped: {type(exc).__name__}")
    return found


def cluster_stories(items: list[dict]) -> list[dict]:
    # Match each wire story to the first item in the cluster, not to a
    # growing bag of words. A growing bag pulls the next headline off the story.
    clusters: list[dict] = []
    for item in sorted(items, key=lambda it: it["when"], reverse=True):
        placed = False
        for cluster in clusters:
            if jaccard(item["toks"], cluster["lead_toks"]) >= 0.28:
                cluster["items"].append(item)
                placed = True
                break
        if not placed:
            clusters.append({"items": [item], "lead_toks": set(item["toks"])})
    now = datetime.now(timezone.utc)
    ranked = []
    for cluster in clusters:
        newest = max(cluster["items"], key=lambda it: it["when"])
        age_h = max(0.0, (now - newest["when"]).total_seconds() / 3600)
        lead = min(cluster["items"], key=lambda it: (len(it["headline"]), -it["when"].timestamp()))
        sources = {it["source"].strip().lower() for it in cluster["items"] if it.get("source")}
        ranked.append(
            {
                "headline": lead["headline"],
                "source": lead["source"],
                "when": newest["when"],
                "score": max(1, len(sources)) * 32 + len(cluster["items"]) * 4 + max(0.0, 30 - age_h),
                "count": len(cluster["items"]),
            }
        )
    ranked.sort(key=lambda it: it["score"], reverse=True)
    return ranked


def choose_story(last_target: str | None, last_headline: str) -> dict | None:
    # Trump, Musk, and MAGA take turns. The interesting story is the strongest
    # cluster in the lane whose turn it is. A lane with nothing today is skipped.
    pools: dict[str, list[dict]] = {name: [] for name in POLITICS_ORDER}
    for item in gather_stories():
        for target in item["targets"]:
            if target in pools:
                pools[target].append(item)
    last_toks = tokens(last_headline)
    best: dict[str, dict] = {}
    for target, group in pools.items():
        for cluster in cluster_stories(group):
            score = cluster["score"]
            if last_toks and jaccard(tokens(cluster["headline"]), last_toks) >= 0.45:
                score -= 40
            row = {**cluster, "target": target, "score": score}
            current = best.get(target)
            if current is None or row["score"] > current["score"]:
                best[target] = row
    if not best:
        return None
    start = 0
    if last_target in POLITICS_ORDER:
        start = (POLITICS_ORDER.index(last_target) + 1) % len(POLITICS_ORDER)
    for step in range(len(POLITICS_ORDER)):
        target = POLITICS_ORDER[(start + step) % len(POLITICS_ORDER)]
        if target in best and best[target]["score"] > 0:
            return best[target]
    ranked = sorted(best.values(), key=lambda it: it["score"], reverse=True)
    return ranked[0]


def strip_leading_emoji(text: str) -> str:
    index = 0
    while index < len(text):
        ch = text[index]
        code = ord(ch)
        cat = unicodedata.category(ch)
        emoji = (
            cat in {"So", "Sk"}
            or code in {0xFE0F, 0x200D, 0x20E3}
            or 0x1F000 <= code <= 0x1FAFF
            or 0x2600 <= code <= 0x27BF
            or 0x2190 <= code <= 0x2BFF
            or 0x1F1E6 <= code <= 0x1F1FF
        )
        if index == 0 and ch.isspace():
            index += 1
            continue
        if emoji:
            index += 1
            continue
        if ch.isspace():
            index += 1
        break
    return text[index:].strip()


