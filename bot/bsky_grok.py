def clean_md(text: str) -> str:
    text = re.sub(r"\[([^\]]+)\]\([^)]+\)", r"\1", text)
    text = text.replace("**", "").replace("`", "")
    text = text.replace("*", "")
    text = re.sub(r"\s+", " ", text).strip()
    return text.strip(" .")


def changelog_sections(path: Path) -> list[tuple[str, str]]:
    text = path.read_text(encoding="utf-8")
    parts = re.split(r"(?m)^## ", text)
    found = []
    for part in parts[1:]:
        heading, _, body = part.partition("\n")
        heading = heading.strip()
        if not heading or heading.lower() in {"unreleased", "changes"}:
            continue
        found.append((heading, body))
    return found


def blurb_of(body: str) -> str:
    title = ""
    fact = ""
    for raw in body.splitlines():
        line = raw.strip()
        if not line or line.startswith("---") or line.startswith("layout:"):
            continue
        if line.startswith("### "):
            if not title:
                title = clean_md(line[4:])
            continue
        if line.startswith("#"):
            continue
        if line.startswith(("- ", "* ")):
            fact = clean_md(line[2:])
            break
        fact = clean_md(line)
        break
    if title and fact and title.lower() not in fact.lower():
        return f"{title}. {fact}"
    return fact or title


def release_text(item: dict) -> str:
    fact = blurb_of(item["body"]) or item["heading"]
    prefix = f"{item['emoji']} {item['name']} updated. "
    suffix = f" The rest of the file can wait.\n{item['link']}"
    sentences = [part.strip() for part in re.split(r"(?<=[.!?])\s+", fact) if part.strip()]
    kept: list[str] = []
    for sentence in sentences:
        trial = " ".join(kept + [sentence]).strip().rstrip(".")
        if len(f"{prefix}{trial}.{suffix}") <= LIMIT:
            kept.append(sentence.strip())
            continue
        break
    if kept:
        fact = " ".join(kept).strip().rstrip(".")
    else:
        while len(f"{prefix}{fact}.{suffix}") > LIMIT and " " in fact:
            fact = " ".join(fact.split()[:-1]).rstrip(" .,;:")
    text = f"{prefix}{fact}.{suffix}"
    if len(text) > LIMIT:
        raise SystemExit(f"Release post is {len(text)} characters, over the {LIMIT} limit.")
    if THREAT_RE.search(text) or SLUR_RE.search(text) or CREDIT_RE.search(text):
        raise SystemExit("Release post failed the safety check.")
    return text


def banner_jpeg() -> Path:
    if not BANNER.is_file():
        raise SystemExit(f"Missing banner {BANNER}")
    dest = STATE_DIR / "images" / "libresky-banner.jpg"
    dest.parent.mkdir(parents=True, exist_ok=True)
    subprocess.run(
        ["ffmpeg", "-y", "-hide_banner", "-loglevel", "error", "-i", str(BANNER), "-frames:v", "1", "-q:v", "4", str(dest)],
        check=True,
    )
    if dest.stat().st_size > 1_000_000:
        raise SystemExit(f"Banner is {dest.stat().st_size} bytes, over the Bluesky limit.")
    return dest


def collect_releases() -> list[dict]:
    found = []
    for src in RELEASES:
        path = src["path"]
        if not path.is_file():
            log(f"release file missing: {path}")
            continue
        for heading, body in changelog_sections(path):
            found.append({**src, "heading": heading, "body": body, "key": f"{src['id']}\t{heading}"})
    return found


def post_release(now: datetime, state: dict, dry_run: bool) -> int:
    found = collect_releases()
    previous = state.get("release") or {}
    seen = [str(item) for item in (previous.get("seen") or [])]
    if not previous.get("baselined"):
        keys = [item["key"] for item in found]
        if dry_run:
            print(f"baseline {len(keys)}")
            for key in keys:
                print(key)
            return 0
        state["release"] = {"baselined": True, "seen": keys, "at": "", "url": "", "heading": ""}
        save_state(state)
        log(f"release baseline {len(keys)} headings, nothing posted")
        return 0
    fresh = [item for item in found if item["key"] not in seen]
    if not fresh:
        log("skip release: no new heading")
        return 0
    last = previous.get("at") or ""
    if last:
        then = datetime.fromisoformat(last)
        if then.tzinfo is None:
            then = then.replace(tzinfo=now.tzinfo)
        if then.astimezone(now.tzinfo).date() == now.date():
            log("skip release: one software note already went up today")
            return 0
    item = fresh[0]
    text = release_text(item)
    if dry_run:
        print(text)
        print(f"chars {len(text)}")
        print(f"key {item['key']}")
        print(f"waiting {len(fresh) - 1}")
        return 0
    latest = last_public_at(state, now)
    if latest is not None and now - latest < QUIET:
        log(f"skip release: a post went up within {int(QUIET.total_seconds() // 60)} minutes")
        return 0
    env = load_env()
    session, token = create_session(env)
    if item["id"] == "libresky":
        url = publish(session, token, text, banner_jpeg(), BANNER_ALT, link=item["link"], width=1200, height=630)
    else:
        url = publish_text(session, token, text)
    seen.append(item["key"])
    state["release"] = {
        "baselined": True,
        "seen": seen,
        "at": now.isoformat(timespec="seconds"),
        "url": url,
        "heading": item["heading"],
        "id": item["id"],
    }
    save_state(state)
    log(f"posted release {item['id']} {url}")
    return 0


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description="Post as The White Witch on Bluesky.")
    parser.add_argument("slot", choices=[*SLOTS, "video", "say", "paypal", "release"])
    parser.add_argument("--dry-run", action="store_true", help="Print the post. Do not write to Bluesky.")
    parser.add_argument("--force", action="store_true", help="Post even if this slot already ran.")
    parser.add_argument("--image", help="JPEG to attach instead of the drawn poster.")
    parser.add_argument("--alt", help="Alt text when --image is used.")
    parser.add_argument("--file", help="mp4 to post with the video command.")
    parser.add_argument("--text-file", help="Caption file for the video command.")
    parser.add_argument("--alt-file", help="Alt text file for the video command.")
    args = parser.parse_args(argv)

    STATE_DIR.mkdir(parents=True, exist_ok=True)
    lock_fh = LOCK_PATH.open("a", encoding="utf-8")
    try:
        fcntl.flock(lock_fh, fcntl.LOCK_EX | fcntl.LOCK_NB)
    except BlockingIOError:
        log(f"skip {args.slot}: another run is already going")
        return 0
    try:
        if args.slot == "video":
            return post_video(args.force, args.dry_run, args.file, args.text_file, args.alt_file)
        if args.slot == "say":
            return post_say(args.force, args.dry_run)
        now = berlin_now()
        state = load_state()
        if args.slot == "paypal":
            return post_paypal(now, state, args.dry_run, args.force)
        if args.slot == "release":
            return post_release(now, state, args.dry_run)
        return post_slot(args.slot, args.force, args.dry_run, args.image, args.alt)
    except SystemExit as err:
        if err.code not in (0, None):
            log(f"fail {args.slot}: {err}")
        raise
    finally:
        fcntl.flock(lock_fh, fcntl.LOCK_UN)


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
