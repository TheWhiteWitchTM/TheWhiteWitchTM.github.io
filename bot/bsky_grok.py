def hook_of(headline: str) -> str:
    text = re.sub(r"\s+", " ", headline).strip()
    text = re.sub(r",?\s+(CEO|sources say|report says|officials say)\b.*$", "", text, flags=re.I)
    text = text.strip().rstrip(".")
    if ":" in text:
        left, right = text.split(":", 1)
        right = right.strip().strip(".")
        if len(left) + len(right) <= 150 and len(right) <= 80:
            text = f"{left.strip()}: {right}"
        else:
            text = left.strip()
    if len(text) > 150:
        text = " ".join(text.split()[:16]).rstrip(" .,;:")
    return text


def compose_politics(story: dict, when: datetime) -> tuple[str, str]:
    mark, barbs = BARBS[story_shape(story)]
    barb = barbs[when.date().toordinal() % len(barbs)]
    hook = hook_of(story["headline"])
    text = f"{mark} {hook}. {barb}"
    while len(text) > LIMIT and " " in hook:
        hook = " ".join(hook.split()[:-1]).rstrip(" .,;:")
        text = f"{mark} {hook}. {barb}"
    if THREAT_RE.search(text) or SLUR_RE.search(text):
        raise SystemExit("Politics line failed the safety check.")
    return text, barb


def wrap_text(text: str, limit: int, max_lines: int) -> str:
    words = text.split()
    lines: list[str] = []
    cur = ""
    index = 0
    while index < len(words) and len(lines) < max_lines:
        word = words[index]
        trial = word if not cur else f"{cur} {word}"
        if len(trial) <= limit:
            cur = trial
            index += 1
            continue
        if cur:
            lines.append(cur)
            cur = ""
            continue
        lines.append(word[: limit - 1].rstrip() + "…")
        index += 1
    if cur and len(lines) < max_lines:
        lines.append(cur)
    if index < len(words) and lines and not lines[-1].endswith("…"):
        last = lines[-1].rstrip(" .,;:")
        if len(last) > limit - 1:
            last = last[: limit - 1].rstrip()
        lines[-1] = last + "…"
    return "\n".join(lines)


def fit_lines(text: str, max_lines: int) -> tuple[str, int]:
    for size, limit in ((40, 32), (34, 38), (28, 46)):
        wrapped = wrap_text(text, limit, max_lines)
        if "…" not in wrapped or size == 28:
            return wrapped, size
    return wrap_text(text, 46, max_lines), 28


def latin_fold(text: str) -> str:
    for src, dst in {"“": '"', "”": '"', "‘": "'", "’": "'", "—": "-", "–": "-", "…": "...", "·": "|"}.items():
        text = text.replace(src, dst)
    return text.encode("ascii", "replace").decode("ascii")


