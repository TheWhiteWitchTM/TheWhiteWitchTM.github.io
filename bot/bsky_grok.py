def skyline(cv: Canvas, rng: random.Random, base: int, color: tuple[int, int, int], light: tuple[int, int, int], x0: int, x1: int, gap: tuple[int, int] | None = None) -> None:
    x = x0
    while x < x1:
        w = rng.randint(40, 96)
        h = rng.randint(40, 170)
        overlaps = gap is not None and not (x + w < gap[0] or x > gap[1])
        if overlaps:
            x += w
            continue
        cv.rect(x, base - h, w - 8, h, color)
        if h > 90:
            wy = base - h + 18
            while wy < base - 24:
                wx = x + 10
                while wx < x + w - 20:
                    if rng.random() < 0.28:
                        cv.rect(wx, wy, 7, 9, light)
                    wx += 18
                wy += 24
        x += w


