def _blend(a: tuple[int, int, int], b: tuple[int, int, int], t: float) -> tuple[int, int, int]:
    return tuple(int(a[i] + (b[i] - a[i]) * t) for i in range(3))  # type: ignore[return-value]


class Canvas:
    def __init__(self) -> None:
        self.buf = bytearray(W * H * 3)

    def get(self, x: int, y: int) -> tuple[int, int, int]:
        i = (y * W + x) * 3
        return self.buf[i], self.buf[i + 1], self.buf[i + 2]

    def put(self, x: int, y: int, color: tuple[int, int, int], cover: float = 1.0) -> None:
        if x < 0 or y < 0 or x >= W or y >= H or cover <= 0:
            return
        if cover >= 1:
            i = (y * W + x) * 3
            self.buf[i : i + 3] = bytes(color)
            return
        mixed = _blend(self.get(x, y), color, cover)
        i = (y * W + x) * 3
        self.buf[i : i + 3] = bytes(mixed)

    def fill(self, color: tuple[int, int, int]) -> None:
        pixel = bytes(color)
        row = pixel * W
        for y in range(H):
            start = y * W * 3
            self.buf[start : start + W * 3] = row

    def vgradient(self, top: tuple[int, int, int], bottom: tuple[int, int, int], y0: int, y1: int) -> None:
        span = max(1, y1 - y0 - 1)
        for y in range(max(0, y0), min(H, y1)):
            t = (y - y0) / span
            color = _blend(top, bottom, t)
            pixel = bytes(color)
            start = (y * W) * 3
            self.buf[start : start + W * 3] = pixel * W

    def rect(self, x: int, y: int, w: int, h: int, color: tuple[int, int, int]) -> None:
        x0, y0 = max(0, x), max(0, y)
        x1, y1 = min(W, x + w), min(H, y + h)
        pixel = bytes(color)
        for yy in range(y0, y1):
            start = (yy * W + x0) * 3
            self.buf[start : start + (x1 - x0) * 3] = pixel * (x1 - x0)

    def stroke_rect(self, x: int, y: int, w: int, h: int, weight: int, color: tuple[int, int, int]) -> None:
        self.rect(x, y, w, weight, color)
        self.rect(x, y + h - weight, w, weight, color)
        self.rect(x, y, weight, h, color)
        self.rect(x + w - weight, y, weight, h, color)

    def circle(self, cx: float, cy: float, r: float, color: tuple[int, int, int]) -> None:
        if r <= 0:
            return
        x0 = max(0, int(cx - r - 2))
        x1 = min(W, int(cx + r + 3))
        y0 = max(0, int(cy - r - 2))
        y1 = min(H, int(cy + r + 3))
        for y in range(y0, y1):
            for x in range(x0, x1):
                d = math.hypot(x + 0.5 - cx, y + 0.5 - cy)
                cover = r - d + 0.5
                if cover <= 0:
                    continue
                self.put(x, y, color, 1.0 if cover >= 1 else cover)

    def polygon(self, pts: list[tuple[float, float]], color: tuple[int, int, int]) -> None:
        if len(pts) < 3:
            return
        ys = [p[1] for p in pts]
        y0 = max(0, int(min(ys)))
        y1 = min(H - 1, int(max(ys)))
        for y in range(y0, y1 + 1):
            crosses: list[float] = []
            for i in range(len(pts)):
                x1, y1p = pts[i]
                x2, y2p = pts[(i + 1) % len(pts)]
                if (y1p <= y < y2p) or (y2p <= y < y1p):
                    if y2p == y1p:
                        continue
                    t = (y + 0.5 - y1p) / (y2p - y1p)
                    crosses.append(x1 + t * (x2 - x1))
            crosses.sort()
            for i in range(0, len(crosses) - 1, 2):
                xa = max(0, int(crosses[i]))
                xb = min(W, int(crosses[i + 1]) + 1)
                for x in range(xa, xb):
                    self.put(x, y, color)

    def write_ppm(self, path: Path) -> None:
        header = f"P6\n{W} {H}\n255\n".encode("ascii")
        path.write_bytes(header + self.buf)


def draw_moon(cv: Canvas, cx: float, cy: float, r: float, phase: float, color: tuple[int, int, int], sky_at) -> None:
    """One disk. The unlit face stays dark, so the terminator does not leave a second crescent."""
    x0 = max(0, int(cx - r - 2))
    x1 = min(W, int(cx + r + 3))
    y0 = max(0, int(cy - r - 2))
    y1 = min(H, int(cy + r + 3))
    new = phase <= 0.03 or phase >= 0.97
    for y in range(y0, y1):
        for x in range(x0, x1):
            relx = (x + 0.5 - cx) / r
            rely = (y + 0.5 - cy) / r
            dist = math.hypot(relx, rely)
            if dist > 1.02:
                continue
            cover = min(1.0, (1.02 - dist) / 0.04) if dist > 0.98 else 1.0
            sky = sky_at(y)
            if new:
                if dist > 0.9:
                    cv.put(x, y, _blend(sky, color, 0.5), cover)
                continue
            if _lit(relx, rely, phase):
                shade = 1.0 - 0.16 * max(0.0, relx * 0.55 + rely * 0.35)
                tone = tuple(max(0, min(255, int(c * shade))) for c in color)
                cv.put(x, y, tone, cover)  # type: ignore[arg-type]
            else:
                cv.put(x, y, _blend(sky, color, 0.14), cover)


def _lit(relx: float, rely: float, phase: float) -> bool:
    if relx * relx + rely * rely > 1:
        return False
    if phase <= 0.03 or phase >= 0.97:
        return False
    if abs(phase - 0.5) < 0.03:
        return True
    half = math.sqrt(max(0.0, 1 - rely * rely))
    # 0 new, 0.25 first quarter (right half), 0.5 full, 0.75 last quarter.
    k = math.cos(phase * 2 * math.pi)  # +1 at new, -1 at full
    edge = k * half
    if phase < 0.5:
        return relx >= edge
    return relx <= -edge


