def load_jokes() -> list[dict]:
    if not JOKE_MANIFEST.exists():
        raise SystemExit(f"No joke deck at {JOKE_MANIFEST}")
    rows = json.loads(JOKE_MANIFEST.read_text(encoding="utf-8"))
    if not isinstance(rows, list) or not rows:
        raise SystemExit("Joke deck is empty")
    seen: set[str] = set()
    for row in rows:
        joke_id = str(row.get("id") or "")
        if not joke_id or joke_id in seen:
            raise SystemExit(f"Bad joke id {joke_id!r}")
        seen.add(joke_id)
        emoji = str(row.get("emoji") or "")
        text = str(row.get("text") or "").strip()
        alt = str(row.get("alt") or "").strip()
        if not emoji or not text or not alt:
            raise SystemExit(f"Joke {joke_id} is missing an emoji, a line, or alt text")
        marks = [ch for ch in emoji if ord(ch) not in {0xFE0F, 0x200D, 0x20E3}]
        if len(marks) != 1 or strip_leading_emoji(emoji) or strip_leading_emoji(text) != text:
            raise SystemExit(f"Joke {joke_id} must enter with one emoji and keep the line plain")
        post = f"{emoji} {text}"
        if len(post) > LIMIT:
            raise SystemExit(f"Joke {joke_id} is {len(post)} characters, over the {LIMIT} limit.")
        if THREAT_RE.search(post) or SLUR_RE.search(post):
            raise SystemExit(f"Joke {joke_id} failed the safety check.")
        image = JOKE_DIR / f"{joke_id}.jpg"
        if not image.is_file():
            raise SystemExit(f"Joke {joke_id} has no picture at {image}")
        if image.stat().st_size > 1_000_000:
            raise SystemExit(f"Joke {joke_id} picture is over the Bluesky limit.")
        row["image"] = str(image)
        row["post"] = post
    return rows


def take_joke(state: dict) -> tuple[dict, list[str]]:
    """One card from a shuffled deck. The deck refills after the last card, without repeating it."""
    jokes = {row["id"]: row for row in load_jokes()}
    previous = state.get("joke") or {}
    deck = [item for item in (previous.get("deck") or []) if item in jokes]
    if not deck:
        last = previous.get("id")
        deck = [item for item in jokes if item != last] or list(jokes)
        random.shuffle(deck)
    joke_id = deck.pop()
    return jokes[joke_id], deck


